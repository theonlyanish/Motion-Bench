const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

function tagsFrom(name, id, cat) {
  const base = name.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim().split(/\s+/);
  const extra = id.replace(/([A-Z])/g, ' $1').toLowerCase().split(/\s+/);
  return [...new Set([...base, ...extra, cat])].filter(Boolean);
}

function parseTypography() {
  const html = fs.readFileSync(path.join(root, 'typography.html'), 'utf8');
  const sections = html.split(/<section class="panel[^"]*" data-panel="/).slice(1);
  return sections.map(function (chunk) {
    const id = chunk.match(/^([^"]+)"/)[1];
    const nameMatch = chunk.match(/class="panel-title">([^<]+)<\/h2>/);
    const hintMatch = chunk.match(/class="panel-hint">([^<]+)<\/p>/);
    return {
      id: id,
      name: nameMatch ? nameMatch[1].trim() : id,
      desc: hintMatch ? hintMatch[1].trim() : '',
      page: '/typography',
      cat: 'typography'
    };
  });
}

function parseScroll() {
  const html = fs.readFileSync(path.join(root, 'scroll.html'), 'utf8');
  const re = /<section class="scroll-block[^"]*" data-anim="([^"]+)"([\s\S]*?)(?=<section class="scroll-block|<\/main>)/g;
  const out = [];
  let m;
  while ((m = re.exec(html))) {
    const id = m[1];
    const chunk = m[2];
    let name = '';
    const label = chunk.match(/anim-label">([^<]+)</);
    const h2plain = chunk.match(/<h2>([^<]+)<\/h2>/);
    const h2class = chunk.match(/<h2 class="[^"]*">([^<]+)<\/h2>/);
    if (label) name = label[1].trim();
    else if (h2plain) name = h2plain[1].trim();
    else if (h2class) name = h2class[1].trim();
    else if (id === 'stickyStack') name = 'Sticky Stack';
    else if (id === 'horizontalScroll') name = 'Horizontal Scroll';
    else if (id === 'staggerList') name = 'Staggered List';
    else if (id === 'perspectiveGrid') name = 'Perspective Grid';
    else if (id === 'imgReveal') name = 'Image Reveal';
    else if (id === 'stagger') name = 'Staggered Letters';
    else name = id.replace(/([A-Z])/g, ' $1').replace(/^./, s => s.toUpperCase());
    out.push({ id, name, page: '/scroll', cat: 'scroll', desc: '' });
  }
  return out;
}

function parseBlocks(file, cat, page) {
  const html = fs.readFileSync(path.join(root, file), 'utf8');
  const re = /data-fx="([^"]+)"[\s\S]*?block-info[\s\S]*?<h2>([^<]+)<\/h2>[\s\S]*?<p>([^<]+)</g;
  if (cat === 'gallery') {
    const gRe = /data-fx="([^"]+)"[\s\S]*?<h2>([^<]+)<\/h2>[\s\S]*?<p>([^<]+)</g;
    const out = [];
    let m;
    while ((m = gRe.exec(html))) {
      out.push({ id: m[1], name: m[2].trim(), desc: m[3].trim(), page, cat });
    }
    return out;
  }
  const out = [];
  let m;
  while ((m = re.exec(html))) {
    out.push({ id: m[1], name: m[2].trim(), desc: m[3].trim(), page, cat });
  }
  return out;
}

function enrich(items) {
  return items.map(function (e) {
    return {
      id: e.id,
      name: e.name,
      cat: e.cat,
      page: e.page,
      desc: e.desc || '',
      tags: tagsFrom(e.name, e.id, e.cat)
    };
  });
}

const all = [
  ...enrich(parseTypography()),
  ...enrich(parseScroll()),
  ...enrich(parseBlocks('gallery.html', 'gallery', '/gallery')),
  ...enrich(parseBlocks('cursor.html', 'cursor', '/cursor')),
  ...enrich(parseBlocks('layout.html', 'layout', '/layout'))
];

const lines = [
  '/**',
  ' * Canonical index of all animation effects.',
  ' * Generated by scripts/build-effects-index.js — re-run after adding effects.',
  ' */',
  'window.EFFECTS_INDEX = ' + JSON.stringify(all, null, 2) + ';',
  ''
];

fs.writeFileSync(path.join(root, 'effects-index.js'), lines.join('\n'));
console.log('Wrote effects-index.js with', all.length, 'effects');
